"""Produce a reproducible BUPT regression, retrieval, and HTTP report."""

import argparse
import hashlib
import importlib.metadata
import json
import os
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path
from xml.etree import ElementTree

from sqlalchemy.engine import make_url

from backend.app.core.config_manager import settings
from scripts.bupt_e2e import run as run_http
from scripts.eval_bupt import CASES

ROOT = Path(__file__).resolve().parents[1]
REPORTS = ROOT / '.bupt-local' / 'reports'
FAULTS = 'backend/tests/services/test_bupt_faults.py'


def _git(*args: str) -> bytes:
    return subprocess.check_output(['git', *args], cwd=ROOT)


def _tree_hash() -> str:
    digest = hashlib.sha256()
    files = sorted(set(_git('ls-files', '--cached', '--others', '--exclude-standard', '-z').split(b'\0')))
    for raw in files:
        if not raw:
            continue
        relative = raw.decode('utf-8')
        file = ROOT / relative
        digest.update(raw + b'\0')
        if file.is_file():
            digest.update(hashlib.sha256(file.read_bytes()).digest())
    return digest.hexdigest()


def dependencies() -> dict:
    versions = {}
    for name in ('fastapi', 'sqlalchemy', 'pymysql', 'redis', 'chromadb', 'mcp', 'httpx', 'pydantic', 'pytest'):
        try:
            versions[name] = importlib.metadata.version(name)
        except importlib.metadata.PackageNotFoundError:
            versions[name] = None
    return versions


def regression(report_dir: Path) -> tuple[dict, bool]:
    xml_file = report_dir / 'pytest.xml'
    database = report_dir / 'test.sqlite3'
    env = {
        **os.environ,
        'SQLALCHEMY_DATABASE_URI': f'sqlite:///{database.as_posix()}',
        'BUPT_RAG_ENABLED': 'false',
        'BUPT_OLLAMA_ENABLED': 'false',
        'AWS_EC2_METADATA_DISABLED': 'true',
    }
    result = subprocess.run(
        [
            sys.executable,
            '-m',
            'pytest',
            '-q',
            '--disable-warnings',
            f'--junitxml={xml_file}',
            FAULTS,
            'backend/tests/services/test_bupt_mcp_wire.py',
            'backend/tests/services/test_bupt_knowledge.py',
            'backend/tests/services/test_bupt_deepseek.py',
            'backend/tests/core/test_env_template.py',
            'backend/tests/services/test_answer_formatting.py',
            'backend/tests/services/providers/test_registry.py',
        ],
        cwd=ROOT,
        env=env,
        check=False,
    )
    # This report is generated by pytest in the fresh local output directory above.
    cases = ElementTree.parse(xml_file).iter('testcase') if xml_file.exists() else []  # noqa: S314
    passed = 0
    outcomes = {}
    failures = []
    for item in cases:
        failure = item.find('failure')
        error = item.find('error')
        issue = failure if failure is not None else error
        outcome = 'failed' if issue is not None else 'skipped' if item.find('skipped') is not None else 'passed'
        passed += outcome == 'passed'
        name = item.get('name', '')
        if 'test_bupt_faults' in item.get('classname', ''):
            outcomes[name] = outcome
        if issue is not None:
            failures.append({'case': name, 'message': issue.get('message')})
    return {'passed': passed, 'fault_cases': outcomes, 'failures': failures}, result.returncode == 0


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--http-base')
    parser.add_argument('--require-redis', action='store_true')
    parser.add_argument('--require-ollama', action='store_true')
    parser.add_argument('--memory-tokenizer', type=Path)
    parser.add_argument('--live-summary', action='store_true')
    args = parser.parse_args()
    report_dir = REPORTS / datetime.now(UTC).strftime('%Y%m%dT%H%M%S%fZ')
    report_dir.mkdir(parents=True)
    summary = {
        'git_sha': _git('rev-parse', 'HEAD').decode().strip(),
        'dirty': bool(_git('status', '--porcelain')),
        'workspace_content_sha256': _tree_hash(),
        'dependencies': dependencies(),
        'configuration': {
            'database_dialect': make_url(settings.SQLALCHEMY_DATABASE_URI).get_backend_name(),
            'redis_configured': bool(settings.BUPT_REDIS_URL),
            'ollama_retrieval': settings.BUPT_OLLAMA_ENABLED,
            'chat_model': settings.BUPT_CHAT_MODEL,
            'embedding_model': settings.BUPT_EMBEDDING_MODEL,
        },
        'dataset_sha256': hashlib.sha256(json.dumps(CASES, separators=(',', ':'), ensure_ascii=False).encode()).hexdigest(),
        'corpus_sha256': hashlib.sha256((ROOT / 'backend/app/services/bupt_knowledge.json').read_bytes()).hexdigest(),
    }
    tests, ok = regression(report_dir)
    summary['mock_and_fault_regression'] = tests
    retrieval = subprocess.run(
        [sys.executable, '-m', 'scripts.eval_bupt'],
        cwd=ROOT,
        capture_output=True,
        text=True,
        check=False,
    )
    summary['retrieval'] = json.loads(retrieval.stdout) if retrieval.stdout else {'failure': 'no evaluation result'}
    ok &= retrieval.returncode == 0
    if args.memory_tokenizer or args.live_summary:
        command = [sys.executable, '-m', 'scripts.eval_bupt_memory']
        if args.memory_tokenizer:
            command.extend(['--tokenizer', str(args.memory_tokenizer)])
        if args.live_summary:
            command.append('--live-summary')
        memory = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, check=False)
        summary['memory'] = json.loads(memory.stdout) if memory.stdout else {'failure': 'no memory result'}
        ok &= memory.returncode == 0
    if args.http_base:
        try:
            summary['http'] = run_http(args.http_base, require_redis=args.require_redis, require_ollama=args.require_ollama)
        except Exception as exc:
            summary['http'] = {'failure': f'{type(exc).__name__}: {exc}'}
            ok = False
    file = report_dir / 'report.json'
    file.write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding='utf-8')
    print(file)
    raise SystemExit(0 if ok else 1)


if __name__ == '__main__':
    main()
